#!/usr/bin/env python3
"""
Update scenario MATRIX.md rows from validated result artifacts.

Intent: Matrix rows should point at real result evidence after validation, while
the verdict text itself remains copied from the LLM/human-authored result file
rather than generated by tooling.
Source: DI-nuhon
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import List, Tuple

from matrix_common import REPO_ROOT, RESULTS_ROOT


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Update scenario MATRIX.md rows from result files.")
    parser.add_argument(
        "--result",
        action="append",
        required=True,
        help="Result path to copy into its scenario matrix. May be passed more than once.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print intended matrix updates without writing files.",
    )
    return parser.parse_args()


def result_coordinates(result_path: Path) -> Tuple[str, str, str, str]:
    """Extract the locked result coordinates from a result file path."""

    try:
        rel_parts = result_path.relative_to(RESULTS_ROOT).parts
    except ValueError as error:
        raise RuntimeError(f"Result is not under {RESULTS_ROOT}: {result_path}") from error
    if len(rel_parts) != 4:
        raise RuntimeError(
            "Result path must have shape "
            "results/<sim-id>/<scenario-id>/<model-id>/<timestamp>.md"
        )
    sim_id, scenario_id, model_id, filename = rel_parts
    if not filename.endswith(".md"):
        raise RuntimeError(f"Result file must be markdown: {result_path}")
    return sim_id, scenario_id, model_id, filename[:-3]


def extract_evidence_verdict(result_path: Path) -> str:
    """Copy the result's Evidence verdict line for MATRIX.md notes."""

    for line in result_path.read_text().splitlines():
        if line.startswith("Evidence verdict:"):
            verdict = line.removeprefix("Evidence verdict:").strip()
            return verdict or "result recorded"
    raise RuntimeError(f"Missing Evidence verdict line: {result_path}")


def split_markdown_row(line: str) -> List[str]:
    """Split a simple markdown table row into trimmed cells."""

    if not line.startswith("|"):
        return []
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def unwrap_code_cell(value: str) -> str:
    """Normalize backtick-wrapped table cells for matching."""

    value = value.strip()
    if value.startswith("`") and value.endswith("`"):
        return value[1:-1]
    return value


def escape_table_cell(value: str) -> str:
    """Escape markdown table separators copied from result verdict text."""

    return value.replace("\n", " ").replace("|", "\\|").strip()


def row_for_result(result_path: Path) -> Tuple[str, str, str]:
    """Build the canonical MATRIX.md row for a result artifact."""

    sim_id, scenario_id, _model_id, _timestamp = result_coordinates(result_path)
    rel_result = result_path.relative_to(REPO_ROOT).as_posix()
    verdict = escape_table_cell(extract_evidence_verdict(result_path))
    row = f"| `{sim_id}` | `{scenario_id}` | `{rel_result}` | run | {verdict} |"
    return scenario_id, sim_id, row


def update_matrix_for_result(result_path: Path, dry_run: bool = False) -> Path:
    """Insert or replace the result row for its scenario matrix."""

    scenario_id, sim_id, new_row = row_for_result(result_path)
    matrix_path = REPO_ROOT / "scenarios" / scenario_id / "MATRIX.md"
    if not matrix_path.exists():
        raise RuntimeError(f"Scenario matrix does not exist: {matrix_path}")

    lines = matrix_path.read_text().splitlines()
    replacement_index = None
    for index, line in enumerate(lines):
        cells = split_markdown_row(line)
        if len(cells) < 2:
            continue
        if unwrap_code_cell(cells[0]) == sim_id and unwrap_code_cell(cells[1]) == scenario_id:
            replacement_index = index
            break

    if replacement_index is None:
        lines.append(new_row)
        action = "append"
    else:
        lines[replacement_index] = new_row
        action = "replace"

    if dry_run:
        print(f"{action}: {matrix_path.relative_to(REPO_ROOT)} -> {new_row}")
        return matrix_path

    matrix_path.write_text("\n".join(lines) + "\n")
    print(f"{action}: {matrix_path.relative_to(REPO_ROOT)}")
    return matrix_path


def main() -> int:
    args = parse_args()
    for result in args.result:
        result_path = Path(result)
        if not result_path.is_absolute():
            result_path = (REPO_ROOT / result_path).resolve()
        update_matrix_for_result(result_path, dry_run=args.dry_run)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
